export function getStageFromPigStatus(status?: string, purpose?: string): PigStage {
  if (!status) return "stage_all";
  const s = status.toUpperCase();
  if (s === "PIGLET") return "stage_suckling";
  if (s === "STARTER") return "stage_nursery";
  if (s === "GROWER" || s === "FINISHER") return "stage_grower_finisher";
  if (
    s === "SOW" || s === "GILT" || s === "BOAR" || s === "BARROW" ||
    s === "PREGNANT" || s === "LACTATING" || s === "NURSING"
  ) {
    return "stage_breeding_stock";
  }
  if (purpose && purpose.toUpperCase() === "BREEDER") return "stage_breeding_stock";
  return "stage_all";
}

