export interface DiagnosisMatchResult {
  disease: DiseaseItem;
  matches: number;
  matchPercent: number;
  totalSymptoms: number;
  matchedWeight: number;
  totalWeight: number;
  matchedPathognomonic: string[];
  isNotifiableAlert: boolean;
}

export function diagnoseSwineDiseases(
  selectedSymptoms: Set<string>,
  stageFilter: PigStage = "stage_all"
): DiagnosisMatchResult[] {
  if (selectedSymptoms.size === 0) return [];

  const results: DiagnosisMatchResult[] = [];

  for (const disease of DISEASES) {
    if (stageFilter !== "stage_all" && disease.stages && disease.stages.length > 0) {
      const matchStage = disease.stages.includes("stage_all") || disease.stages.includes(stageFilter);
      if (!matchStage) continue;
    }

    const matchedSymptoms = disease.symptomKeys.filter((sk) => selectedSymptoms.has(sk));
    if (matchedSymptoms.length === 0) continue;

    const matchedWeight = matchedSymptoms.reduce((sum, sk) => sum + getSymptomWeight(sk), 0);
    const totalWeight = Math.max(1.0, disease.symptomKeys.reduce((sum, sk) => sum + getSymptomWeight(sk), 0));
    const matchPercent = Math.min(100, Math.max(1, Math.round((matchedWeight / totalWeight) * 100)));

    const matchedPathognomonic = matchedSymptoms.filter((sk) => isPathognomonic(sk));
    const isNotifiableAlert = Boolean(
      disease.isNotifiable &&
      (matchPercent >= 35 || matchedPathognomonic.length > 0 || matchedSymptoms.length >= 2)
    );

    results.push({
      disease,
      matches: matchedSymptoms.length,
      matchPercent,
      totalSymptoms: disease.symptomKeys.length,
      matchedWeight,
      totalWeight,
      matchedPathognomonic,
      isNotifiableAlert,
    });
  }

  results.sort((a, b) => {
    if (a.isNotifiableAlert !== b.isNotifiableAlert) {
      return a.isNotifiableAlert ? -1 : 1;
    }
    if (b.matchPercent !== a.matchPercent) {
      return b.matchPercent - a.matchPercent;
    }
    return b.matchedWeight - a.matchedWeight;
  });

  return results;
}
