export type SeverityLevel = "LOW" | "MODERATE" | "HIGH" | "CRITICAL";

export type PigStage =
  | "stage_all"
  | "stage_suckling"
  | "stage_nursery"
  | "stage_grower_finisher"
  | "stage_breeding_stock";

